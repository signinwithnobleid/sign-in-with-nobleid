#!/usr/bin/env node
/**
 * Builds the button set in brand/buttons/ and the white mark.
 *
 *   node scripts/build-buttons.mjs           write the files
 *   node scripts/build-buttons.mjs --check   exit 1 if any file on disk differs
 *
 * Sources, both vector, so every size stays sharp:
 * - the mark: brand/nobleid-mark.svg (the master; recoloured only to white);
 * - the labels: scripts/button-labels.json, the outlined text of the original
 *   40 px buttons, scaled to each size. No font is needed and none is embedded.
 * Geometry and colours: scripts/button-spec.mjs. Output is deterministic.
 * The original seven files in brand/ are left as they are.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { LABELS, MARK, SIZES, THEMES, everyButton, padding, radius } from "./button-spec.mjs";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const BRAND = path.join(ROOT, "brand");
const OUT = path.join(BRAND, "buttons");

const masterSvg = fs.readFileSync(path.join(BRAND, "nobleid-mark.svg"), "utf8");
const markPath = /<path fill="#009966" transform="translate\(0 1080\) scale\(0\.1 -0\.1\)" d="([^"]+)"\/>/.exec(masterSvg);
if (!markPath) throw new Error("brand/nobleid-mark.svg: mark path not found");
const MARK_D = markPath[1];
const MARK_W = 1112;
const MARK_H = 1080;

const src = JSON.parse(fs.readFileSync(path.join(ROOT, "scripts", "button-labels.json"), "utf8"));

/** Ink extent of an absolute M/L/H/V/Q/Z path (control points included, which bound the curve). */
function inkX(d) {
  let min = Infinity;
  let max = -Infinity;
  const re = /([MLHVQZ])([^MLHVQZ]*)/g;
  let m;
  while ((m = re.exec(d))) {
    const n = (m[2].match(/-?\d+(?:\.\d+)?/g) || []).map(Number);
    if (m[1] === "V" || m[1] === "Z") continue;
    const xs = m[1] === "H" ? n : n.filter((_, i) => i % 2 === 0);
    for (const x of xs) {
      if (x < min) min = x;
      if (x > max) max = x;
    }
  }
  return [min, max];
}

/** Label advance width at the source size: what the original button allotted it (pad 12 + mark 22.65 + gap 10 … pad 16). */
const LABEL = {};
for (const [key, l] of Object.entries(src.labels)) {
  const advance = l.sourceWidth - src.originX - 16;
  const [, right] = inkX(l.d);
  if (right > src.originX + advance + 0.5) throw new Error(`${key}: ink runs past its advance`);
  LABEL[key] = { d: l.d, advance };
}

const f = (n) => (Math.round(n * 100) / 100).toFixed(2).replace(/\.?0+$/, "") || "0";
const k5 = (n) => n.toFixed(5).replace(/\.?0+$/, "");

function markGroup(x, y, width, colour) {
  const s = width / MARK_W;
  return `<g transform="translate(${f(x)} ${f(y)}) scale(${k5(s)})" fill="${colour}"><path transform="translate(0 ${MARK_H}) scale(0.1 -0.1)" d="${MARK_D}"/></g>`;
}

function svgButton({ label, theme, shape, size }) {
  const t = THEMES[theme];
  const s = SIZES[size];
  const name = LABELS[label];
  const h = s.h;
  const markH = (s.mark * MARK_H) / MARK_W;
  let w;
  let body;
  if (label === "icon") {
    w = h;
    body = markGroup((h - s.mark) / 2, (h - markH) / 2, s.mark, MARK[t.mark]);
  } else {
    const [padL, padR] = padding(shape, size);
    const k = s.font / src.fontSize;
    const textX = padL + s.mark + s.gap;
    w = Math.ceil(textX + LABEL[label].advance * k + padR);
    // Cap height centred on the button's middle line.
    const baseline = h / 2 + (src.capHeight * k) / 2;
    const tx = textX - src.originX * k;
    const ty = baseline - src.baseline * k;
    body =
      markGroup(padL, (h - markH) / 2, s.mark, MARK[t.mark]) +
      `<g transform="translate(${f(tx)} ${f(ty)}) scale(${k5(k)})" fill="${t.text}"><path d="${LABEL[label].d}"/></g>`;
  }
  const r = radius(shape, h);
  const rx = r === 0 ? "" : ` rx="${f(Math.max(0, r - 0.5))}"`;
  const fill = t.bg || "none";
  const rect = `<rect x="0.5" y="0.5" width="${w - 1}" height="${h - 1}"${rx} fill="${fill}" stroke="${t.border}"/>`;
  return {
    width: w,
    height: h,
    svg: `<svg xmlns="http://www.w3.org/2000/svg" width="${w}" height="${h}" viewBox="0 0 ${w} ${h}" role="img" aria-label="${name}"><title>${name}</title>${rect}${body}</svg>\n`,
  };
}

const files = new Map();
const manifest = [];
for (const b of everyButton()) {
  const { svg, width, height } = svgButton(b);
  files.set(path.join(OUT, b.file), svg);
  manifest.push({ file: b.file, label: b.label, theme: b.theme, shape: b.shape, size: b.size, width, height });
}
files.set(
  path.join(OUT, "manifest.json"),
  JSON.stringify({ _comment: "Generated by scripts/build-buttons.mjs. Every button file with its size in px.", buttons: manifest }, null, 1) + "\n"
);
// The white mark: the master, recoloured, nothing else changed.
files.set(path.join(BRAND, "nobleid-mark-white.svg"), masterSvg.replace('fill="#009966"', 'fill="#FFFFFF"'));

const check = process.argv.includes("--check");
let stale = 0;
if (!check) fs.mkdirSync(OUT, { recursive: true });
for (const [file, content] of files) {
  const now = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : null;
  if (now === content) continue;
  stale++;
  if (check) console.error(`out of date: ${path.relative(ROOT, file)}`);
  else fs.writeFileSync(file, content);
}
if (check) {
  const extra = fs.existsSync(OUT) ? fs.readdirSync(OUT).filter((n) => !files.has(path.join(OUT, n))) : [];
  for (const n of extra) console.error(`not generated: brand/buttons/${n}`);
  if (stale || extra.length) process.exit(1);
  console.log(`brand/buttons: ${files.size - 2} buttons up to date`);
} else {
  console.log(`wrote ${stale} of ${files.size} files (${files.size - 2} buttons, manifest, white mark)`);
}
